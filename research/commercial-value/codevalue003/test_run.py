@pytest.mark.parametrize('length',[65,127,128,129,255,300])
def test_all_target_bytes_once_and_correct_alignment(length):
    raw=bytes(i%256 for i in range(length))
    chunks=list(blocks(raw))
    assert b''.join(bytes(gold) for _,gold in chunks)==raw[64:]
    for context,gold in chunks:
        assert 64<=len(context)<=127
        assert context[64:]==gold[:-1]

class RepeatLast(torch.nn.Module):
    def forward(self,x):
        return torch.nn.functional.one_hot(x,256).float()*20

def test_actual_neural_denominator_includes_partial_last_block():
    r=neural_file(RepeatLast(),b'\0'*300,'cpu',completion=False,batch=3)
    assert r['targets']==236 and r['accuracy']==1 and r['top5_accuracy']==1
    assert r['nll']<1e-5

def test_completion_is_free_running_with_changed_suffix():
    # Observe the same prefix, feed only generated bytes back. No oracle suffix.
    torch.set_num_threads(2)
    raw=b'\0'*1024
    clean=neural_file(RepeatLast(),raw,'cpu',completion=True)
    poisoned=bytearray(raw);poisoned[129]=1
    changed=neural_file(RepeatLast(),bytes(poisoned),'cpu',completion=True)
    assert clean['offers'][0]['position']==changed['offers'][0]['position']==128
    assert clean['offers'][0]['generated_hex']==changed['offers'][0]['generated_hex']=='00'*32
    assert clean['offers'][0]['exact']['4']==1 and changed['offers'][0]['exact']['4']==0
    assert len(set(offers(raw)))==512
    with pytest.raises(ValueError):offers(b'x'*130)

def test_probability_metrics_have_known_values():
    r=initial();p=np.full((2,256),1/256)
    add_predictions(r,p,[0,0]);finish(r)
    assert r['nll']==pytest.approx(np.log(256))
    assert r['brier']==pytest.approx(255/256)
