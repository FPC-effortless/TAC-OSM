@pytest.mark.parametrize('order',[3,6])
def test_classical_fit_only_normalized_and_immutable(order):
    m=Counts([b'abcd'*100],order)
    before=m.distribution(b'abc').copy()
    assert np.isclose(before.sum(),1) and (before>0).all()
    m.distribution(b'xxxyyy')
    assert np.array_equal(before,m.distribution(b'abc'))

