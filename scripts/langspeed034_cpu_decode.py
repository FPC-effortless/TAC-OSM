from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
for root in (ROOT,ROOT/"src",ROOT/"research/mathematical-engineering/langbase024"):
    sys.path.insert(0,str(root))
import torch
from torch.nn import functional as F
from byte_next_reference import train_count_model,law
from scripts.langcompare029_sampling import fit_sources,schedule_receipt
from scripts.langcompare031_cpu_fit import cold_reload
from scripts.langcompare029_preflight import parameter_count

CHECKSUMS={
 "tac_context026":"897435d2db494a5de10ee46a159f0050a651c916f67718165e08f894f6c84e5e",
 "bdh_official":"516e82b75792de6727940832acf24e5d3b411758d8c8efc5c68cdc24e498786d",
 "causal_transformer":"ab36031debf5b68abc25dfc3c8ca362110854b49877e2b2f19e3df806e7786ae"}
COUNTS={"tac_context026":500122,"bdh_official":501504,"causal_transformer":496960}
NEURAL=tuple(CHECKSUMS)
ALL=NEURAL
SEED=1701
LENGTHS=(32,128)
GENERATE=2
REPEATS=2
PREFILL_REPEATS=1

def original_path(folder,arm):
    found=list(folder.rglob(f"{arm}_seed{SEED}_fit320.pt"))
    if len(found)!=1:raise ValueError(f"{arm}: missing or duplicate original trained checkpoint")
    path=found[0]
    if path.is_symlink():raise ValueError("refuse symbolic original checkpoint path")
    raw=path.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=CHECKSUMS[arm]:
        raise ValueError(f"{arm}: original SHA256 mismatch")
    return raw

def load_models(checkpoints,bdh_source,fit):
    order=schedule_receipt(fit,SEED,steps=320)["sample_order_sha256"]
    models={}
    for arm in NEURAL:
        raw=original_path(checkpoints,arm)
        m=cold_reload(raw,arm,SEED,bdh_source,order).eval()
        size=parameter_count(m)
        if size!={"trainable":COUNTS[arm],"deployed":COUNTS[arm]}:
            raise ValueError(f"{arm}: original trained model parameter count changed")
        models[arm]=m
    return models

def logits(model,prefix):
    b=torch.as_tensor([prefix],dtype=torch.long,device="cpu")
    out=model(b)
    if not torch.is_tensor(out):
        out=out.logits if hasattr(out,"logits") else out[0]
    if out.shape!=(1,len(prefix),256) or not torch.isfinite(out).all().item():
        raise ValueError("original neural logits invalid or geometry changed")
    return out[0,-1]

def next_byte(arm,models,p3,prefix):
    if arm=="p3_fit_counts":
        p=law(p3,bytes(prefix[-3:]),3)
        return max(range(256),key=lambda i:p[i])
    l=logits(models["tac_context026" if arm=="tac_p3_75_fixed" else arm],prefix)
    if arm=="tac_p3_75_fixed":
        probs=F.softmax(l.double(),dim=-1)
        p=torch.tensor(law(p3,bytes(prefix[-3:]),3),dtype=torch.float64)
        return int((0.25*probs+0.75*p).argmax().item())
    return int(l.argmax().item())

def warmup(models,p3,prompt):
    with torch.inference_mode():
        for arm in ALL:
            for _ in range(2):
                next_byte(arm,models,p3,list(prompt))

def prefill_bench(models,prompt):
    # One neural call computes all input positions; no decoding cache in this code.
    results={}
    with torch.inference_mode():
        for arm in NEURAL:
            m=models[arm]
            r=[]
            for length in LENGTHS:
                x=torch.tensor([list(prompt[:length])],dtype=torch.long)
                for _ in range(1):m(x)
                times=[]
                for _ in range(PREFILL_REPEATS):
                    t0=time.perf_counter_ns()
                    y=m(x)
                    elapsed=(time.perf_counter_ns()-t0)/1e6
                    if isinstance(y,tuple):y=y[0]
                    elif hasattr(y,"logits"):y=y.logits
                    if y.shape!=(1,length,256):raise ValueError("prefill output shape mismatch")
                    times.append(elapsed)
                r.append({"context_bytes":length,
                          "median_full_forward_ms":statistics.median(times),
                          "min_ms":min(times),"max_ms":max(times),
                          "num_timed_runs":len(times)})
            results[arm]=r
    return results

def generation_bench(models,p3,prompt):
    # No prompt prefill cost in this number: only repeated full-context evaluations.
    # Every produced output byte causes a forward over the LAST <=128 bytes.
    results={}
    with torch.inference_mode():
        for prompt_len in (32,128):
            grouped={arm:[] for arm in ALL}
            for repetition in range(REPEATS):
                arms=ALL[repetition%len(ALL):]+ALL[:repetition%len(ALL)]
                for arm in arms:
                    prefix=list(prompt[:prompt_len])
                    steps=[]
                    output=[]
                    for index in range(GENERATE):
                        ctx=prefix[-128:]
                        t0=time.perf_counter_ns()
                        y=next_byte(arm,models,p3,ctx)
                        dt=(time.perf_counter_ns()-t0)/1e6
                        if not (0<=y<256) or not math.isfinite(dt):
                            raise ValueError("invalid generated byte or timing")
                        steps.append(dt)
                        output.append(y)
                        prefix.append(y)
                    grouped[arm].append({
                        "generated_bytes":len(output),
                        "generated_sha256":hashlib.sha256(bytes(output)).hexdigest(),
                        "per_step_latency_ms":steps,
                        "total_ms":sum(steps)})
            for arm,rows in grouped.items():
                if len(rows)!=REPEATS:raise ValueError("missing repeated timing samples")
                if len({r["generated_sha256"] for r in rows})!=1:
                    raise ValueError("CPU inference generated different outputs between repeated runs")
                per_token=[r["total_ms"]/GENERATE for r in rows]
                med=statistics.median(per_token)
                key=f"prompt_{prompt_len}/{arm}"
                results[key]={"prompt_bytes":prompt_len,"model":arm,
                  "generated_bytes_per_repetition":GENERATE,
                  "repetitions":REPEATS,
                  "median_ms_per_generated_byte":med,
                  "tokens_per_second_approx":1000/med,
                  "min_ms_per_byte":min(per_token),
                  "max_ms_per_byte":max(per_token),
                  "raw_step_wall_ms_by_repetition":[r["per_step_latency_ms"] for r in rows],
                  "generated_sha256":rows[0]["generated_sha256"]}
    return results

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--checkpoints",required=True,type=Path)
    p.add_argument("--bdh-source",required=True,type=Path)
    p.add_argument("--output",required=True,type=Path)
    a=p.parse_args()
    if a.output.exists():raise FileExistsError("refuse overwrite original benchmark receipt")
    if torch.cuda.is_initialized():raise RuntimeError("no GPU access in CPU speed experiment")
    torch.set_num_threads(2)
    torch.set_num_interop_threads(1)
    fit=fit_sources()
    prompt=next(iter([fit[name] for name in sorted(fit) if len(fit[name])>=192]))
    models=load_models(a.checkpoints,a.bdh_source,fit)
    # Do not construct the P3 counts model in this neural-only latency comparison.
    # Building source-wide counts is unrelated work and stalled earlier runners.
    p3=None
    # Separate warmups inside prefill_bench; no extra model initialization forwards.
    prefill=prefill_bench(models,prompt)
    gen=generation_bench(models,p3,prompt)
    result={"study":"LANGSPEED034","status":"ACTUAL_FROZEN_TRAINED_CPU_DECODE_BENCH",
        "seed":SEED,"no_training":True,"original_checkpoint_sha256":CHECKSUMS,
        "source":"publisher authenticated CPython FIT bytes, no DEV/TEST",
        "source_sha256":hashlib.sha256(prompt[:128]).hexdigest(),
        "model_parameters":COUNTS,"cpu_threads":torch.get_num_threads(),
        "torch_version":torch.__version__,"python":platform.python_version(),
        "platform":platform.platform(),"processor":platform.processor(),
        "mode":"eval+inference_mode, eager PyTorch float32, batch=1",
        "p3_and_hybrid_speed":"NOT_RUN_SEPARATE_CPU_PROTOCOL",
        "autoregressive_decode":"greedy, repeated whole available prefix; sliding last128 bytes; no incremental state/KV cache for any neural model",
        "prefill":"one forward of full 16/64/128 input; separate from decode",
        "prefill_neural":prefill,"generation":gen,
        "no_optimized_state_claim":True,"gpu_minutes":0,"protected_TEST":"NOT_ACCESSED"}
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_text(json.dumps(result,sort_keys=True,indent=2,allow_nan=False)+"\n")
    summary={k:{"ms_per_byte":round(v["median_ms_per_generated_byte"],4),
                "bytes_per_second":round(v["tokens_per_second_approx"],2)} for k,v in gen.items()}
    print(json.dumps({"study":result["study"],"status":result["status"],
                      "per_arm_decode_summary":summary,
                      "prefill_neural":prefill},indent=2,sort_keys=True),flush=True)

if __name__=="__main__":main()
