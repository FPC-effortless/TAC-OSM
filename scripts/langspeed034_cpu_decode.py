"""LANGSPEED034: source-pinned, trained, CPU decode-speed comparison.

Benchmark ACTUAL 500K frozen LANGCOMPARE031 trained checkpoints (seed1701).
This measures implementations AS SHIPPED: TAC026/official BDH/Transformer have
no accepted persistent generation cache API in this study. Each generated byte
recomputes the entire available <=128-byte context. DO NOT claim optimized
streaming-state decode or Transformer KV-cache superiority from this result.

P3/hybrid runtime is deliberately excluded from this neural-only test.
No training, gradients, calibration, DEV scoring, protected TEST or GPU.
"""
