"""Account complete fixed-exposure DEV-054 main/audit/smoke/demo work."""
import json
from pathlib import Path
from run_learned_belief_dev052b import write
ROOT=Path(__file__).resolve().parents[1]


def counts(directory):
    directory=Path(directory); c=json.loads((directory/'common.json').read_text())
    streams=json.loads((directory/'streams.json').read_text())
    reports=[json.loads(p.read_text()) for p in directory.glob('seed*/report.json')]
    result={'optimizer_updates':0,'probe_executions':0,'probe_actions':0,
            'coupon_executions':sum(len(rows)*32 for rows in streams.values()),
            'coupon_actions':sum(len(o['calls']) for rows in streams.values() for row in rows for o in row['observations']),
            'materialized_rate_target_components':sum(len(rows)*33*3 for rows in streams.values())}
    cells=[cell for arms in c['baselines'].values() for cell in arms.values()]
    for r in reports:
        for cell in r['arms'].values():
            assert cell['status']=='COMPLETED'
            result['optimizer_updates']+=cell['training']['updates']
            cells.extend(cell['evaluation'].values())
    result['probe_executions']=sum(len(cell['rows']) for cell in cells)
    result['probe_actions']=sum(len(row['calls']) for cell in cells for row in cell['rows'])
    return result


def account():
    out=ROOT/'results/dev054'; main=counts(out);smoke=counts('/workspace/scratch/dev054-smoke')
    c=json.loads((out/'common.json').read_text());a=json.loads((out/'audit.json').read_text())
    sc=json.loads(Path('/workspace/scratch/dev054-smoke/common.json').read_text());sa=json.loads(Path('/workspace/scratch/dev054-smoke/audit.json').read_text())
    demo=json.loads((out/'live-demo.json').read_text())
    demo_actions=sum(len(o['calls']) for o in demo['public_observations'])+sum(len(e['native_probe']['calls']) for e in demo['events'] if 'native_probe' in e)
    # Each main/smoke observation+probe action is generated once, regenerated by
    # audit once, and replayed through separate accounting once. Training twice.
    result={'study':'DEV-054','accepted_main':main,'disjoint_smoke':smoke,
            'registered_main_audit_optimizer_updates':2*main['optimizer_updates'],
            'with_smoke_optimizer_updates':2*(main['optimizer_updates']+smoke['optimizer_updates']),
            'native_actions_main_reconstruction_primitive':3*(main['coupon_actions']+main['probe_actions']),
            'native_actions_with_smoke_demo':3*(main['coupon_actions']+main['probe_actions']+smoke['coupon_actions']+smoke['probe_actions'])+demo_actions,
            'main_audit_process_seconds':c['elapsed_seconds']+a['elapsed_seconds'],
            'main_audit_smoke_process_seconds':c['elapsed_seconds']+a['elapsed_seconds']+sc['elapsed_seconds']+sa['elapsed_seconds'],
            'training_target_component_exposures_main_audit':2*15*1024*32*33*2,
            'note':'Process elapsed time, not CPU-seconds. Full pytest, interactive engineering, retrospective bootstrap/reporting, profiling and demo elapsed time additional; their logs/raw records retained. Native action accounting includes all accepted/smoke reconstruction and separate primitive replay, plus demo. No industrial fixture setup cost or power measured.'}
    assert a['separate_probe_actions']==main['probe_actions']
    assert a['separate_coupon_actions']==main['coupon_actions']
    write(ROOT/'research/dev054/resource-accounting.json',result)
    print(json.dumps(result,indent=2))


if __name__=='__main__':account()
